"""3D CFD for FFR: OpenFOAM case export, result read-back and 1D-3D outlet coupling.

The case solves steady incompressible laminar Navier-Stokes (simpleFoam, Newtonian
blood) in the lumen built by :mod:`vessel_code.ffr.mesh3d`, with boundary conditions
consistent with the 1D model so the two can be compared directly:

  inlet      static pressure Pa (kinematic p = Pa / rho), pressureInletVelocity
  outlets    volumetric flow from the converged 1D solution (flowRateOutletVelocity)
  wall       no slip

The microvascular resistances R_i of the 1D calibration are stored in
``ffr3d_case.json``; ``update-flows`` re-sets the outlet flows to
Q_i = (P_i^3D - Pv) / R_i from the 3D outlet pressures (fixed-point 1D-3D coupling;
2-3 outer iterations are usually enough because the flow change is a few percent).

Targets OpenFOAM.com (ESI) v2006 or newer: run ``./Allrun`` inside the case
(blockMesh, surfaceFeatureExtract, snappyHexMesh, checkMesh, simpleFoam, sampling).
For OpenFOAM.org v11+, replace ``simpleFoam`` by ``foamRun -solver incompressibleFluid``.

CLI:
  python -m vessel_code.ffr.openfoam results --case <out>/cfd3d      # FFR_3D along centreline + figure
  python -m vessel_code.ffr.openfoam update-flows --case <out>/cfd3d # coupling step, then rerun simpleFoam
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from vessel_code.ffr.mesh3d import LumenSurface, write_stl

MMHG = 133.322
_HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by vessel_code.ffr.openfoam (PPCAR-Net FFR branch)
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    object      {obj};
}}
"""


def _write(path: Path, cls: str, obj: str, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(_HEADER.format(cls=cls, obj=obj) + body.strip() + "\n")


def _vec(v) -> str:
    return "(" + " ".join(f"{float(x):.9g}" for x in v) + ")"


def write_openfoam_case(result, surface: LumenSurface, case_dir, *, refinement_level: int = 2,
                        boundary_layers: int = 3, iterations: int = 3000, n_procs: int = 8) -> Path:
    case = Path(case_dir)
    case.mkdir(parents=True, exist_ok=True)
    cfg = result.config
    rho, mu = cfg.rho, cfg.mu
    nu = mu / rho
    (case / "constant" / "triSurface").mkdir(parents=True, exist_ok=True)
    write_stl(surface, case / "constant" / "triSurface" / "lumen.stl")
    patches = [n for k, n in enumerate(surface.patch_names) if np.any(surface.face_patch == k)]
    outlets = [n for n in patches if n.startswith("outlet")]

    # --- background mesh: target cell = voxel; background = target * 2^level
    target_m = surface.voxel_mm * 1e-3
    bg = target_m * 2 ** refinement_level
    v = surface.vertices_mm * 1e-3
    lo, hi = v.min(0) - 3 * bg, v.max(0) + 3 * bg
    cells = np.maximum(np.ceil((hi - lo) / bg).astype(int), 1)
    hi = lo + cells * bg
    _write(case / "system" / "blockMeshDict", "dictionary", "blockMeshDict", f"""
convertToMeters 1;
vertices
(
    {_vec([lo[0], lo[1], lo[2]])} {_vec([hi[0], lo[1], lo[2]])} {_vec([hi[0], hi[1], lo[2]])} {_vec([lo[0], hi[1], lo[2]])}
    {_vec([lo[0], lo[1], hi[2]])} {_vec([hi[0], lo[1], hi[2]])} {_vec([hi[0], hi[1], hi[2]])} {_vec([lo[0], hi[1], hi[2]])}
);
blocks ( hex (0 1 2 3 4 5 6 7) ({cells[0]} {cells[1]} {cells[2]}) simpleGrading (1 1 1) );
edges ();
boundary ( background {{ type patch; faces ( (3 7 6 2) (0 4 7 3) (2 6 5 1) (1 5 4 0) (0 3 2 1) (4 5 6 7) ); }} );
""")
    # A point well inside the lumen: on the main centreline away from both ends and lesions.
    main = result.branches[0]
    lesion_idx = {i for l in main.lesions for i in range(l.i0, l.i1 + 1)}
    candidates = [i for i in range(len(main.ffr) // 8, len(main.ffr) // 2) if i not in lesion_idx] or [len(main.ffr) // 4]
    inside = main.xyz_mm[candidates[0]] * 1e-3 + np.array([1.234e-6, 2.345e-6, 3.456e-6])
    region_lines = "\n".join(f"                {n} {{ level ({refinement_level} {refinement_level}); patchInfo {{ type patch; }} }}"
                             for n in patches if n != "wall")
    layer_lines = f"        \"lumen_wall\" {{ nSurfaceLayers {boundary_layers}; }}" if boundary_layers > 0 else ""
    _write(case / "system" / "surfaceFeatureExtractDict", "dictionary", "surfaceFeatureExtractDict", """
lumen.stl
{
    extractionMethod    extractFromSurface;
    includedAngle       150;
    writeObj            no;
}
""")
    _write(case / "system" / "snappyHexMeshDict", "dictionary", "snappyHexMeshDict", f"""
castellatedMesh true;
snap            true;
addLayers       {"true" if boundary_layers > 0 else "false"};
geometry
{{
    lumen.stl {{ type triSurfaceMesh; name lumen; }}
}}
castellatedMeshControls
{{
    maxLocalCells 5000000; maxGlobalCells 60000000; minRefinementCells 10;
    maxLoadUnbalance 0.10; nCellsBetweenLevels 3;
    features ( {{ file "lumen.eMesh"; level {refinement_level}; }} );
    refinementSurfaces
    {{
        lumen
        {{
            level ({refinement_level} {refinement_level});
            patchInfo {{ type wall; }}
            regions
            {{
{region_lines}
            }}
        }}
    }}
    resolveFeatureAngle 30;
    refinementRegions {{}}
    locationInMesh {_vec(inside)};
    allowFreeStandingZoneFaces true;
}}
snapControls
{{
    nSmoothPatch 3; tolerance 2.0; nSolveIter 100; nRelaxIter 5;
    nFeatureSnapIter 10; implicitFeatureSnap false; explicitFeatureSnap true; multiRegionFeatureSnap false;
}}
addLayersControls
{{
    relativeSizes true;
    layers
    {{
{layer_lines}
    }}
    expansionRatio 1.2; finalLayerThickness 0.4; minThickness 0.1; nGrow 0;
    featureAngle 120; nRelaxIter 3; nSmoothSurfaceNormals 1; nSmoothNormals 3; nSmoothThickness 10;
    maxFaceThicknessRatio 0.5; maxThicknessToMedialRatio 0.3; minMedialAxisAngle 90;
    nBufferCellsNoExtrude 0; nLayerIter 50;
}}
meshQualityControls
{{
    maxNonOrtho 65; maxBoundarySkewness 20; maxInternalSkewness 4; maxConcave 80; minVol 1e-30;
    minTetQuality 1e-30; minArea -1; minTwist 0.02; minDeterminant 0.001; minFaceWeight 0.05;
    minVolRatio 0.01; minTriangleTwist -1; nSmoothScale 4; errorReduction 0.75;
    relaxed {{ maxNonOrtho 75; }}
}}
mergeTolerance 1e-6;
""")
    sample_points = []
    sample_index = []
    for b in result.branches.values():
        for i in range(b.start, len(b.ffr)):
            sample_points.append(b.xyz_mm[i] * 1e-3)
            sample_index.append((b.index, i))
    points_txt = "\n".join("            " + _vec(p) for p in sample_points)
    patch_avg = "\n".join(f"""    pAvg_{n}
    {{
        type surfaceFieldValue; libs (fieldFunctionObjects); writeControl writeTime; writeFields false;
        regionType patch; name lumen_{n}; operation areaAverage; fields (p);
    }}""" for n in patches if n != "wall")
    _write(case / "system" / "controlDict", "dictionary", "controlDict", f"""
application     simpleFoam;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {iterations};
deltaT          1;
writeControl    timeStep;
writeInterval   {iterations};
purgeWrite      1;
writeFormat     ascii;
writePrecision  10;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable true;
functions
{{
    sampleCentreline
    {{
        type sets; libs (sampling); writeControl writeTime; interpolationScheme cellPoint; setFormat raw;
        fields (p U);
        sets
        {{
            centreline
            {{
                type points; axis xyz; ordered true;
                points
                (
{points_txt}
                );
            }}
        }}
    }}
{patch_avg}
}}
""")
    _write(case / "system" / "fvSchemes", "dictionary", "fvSchemes", """
ddtSchemes { default steadyState; }
gradSchemes { default Gauss linear; grad(U) cellLimited Gauss linear 1; }
divSchemes { default none; div(phi,U) bounded Gauss linearUpwindV grad(U); div((nuEff*dev2(T(grad(U))))) Gauss linear; }
laplacianSchemes { default Gauss linear limited corrected 0.33; }
interpolationSchemes { default linear; }
snGradSchemes { default limited corrected 0.33; }
wallDist { method meshWave; }
""")
    _write(case / "system" / "fvSolution", "dictionary", "fvSolution", """
solvers
{
    p { solver GAMG; smoother GaussSeidel; tolerance 1e-8; relTol 0.05; }
    U { solver smoothSolver; smoother symGaussSeidel; tolerance 1e-9; relTol 0.1; }
}
SIMPLE
{
    consistent yes;
    nNonOrthogonalCorrectors 1;
    residualControl { p 1e-6; U 1e-7; }
}
relaxationFactors { equations { U 0.7; ".*" 0.7; } fields { p 0.5; } }
""")
    _write(case / "system" / "decomposeParDict", "dictionary", "decomposeParDict",
           f"numberOfSubdomains {n_procs};\nmethod scotch;\n")
    _write(case / "system" / "meshQualityDict", "dictionary", "meshQualityDict",
           "#includeEtc \"caseDicts/mesh/generation/meshQualityDict\"\n")
    for name in ("momentumTransport", "turbulenceProperties"):
        _write(case / "constant" / name, "dictionary", name, "simulationType laminar;\n")
    _write(case / "constant" / "transportProperties", "dictionary", "transportProperties",
           f"transportModel Newtonian;\nnu {nu:.9g};\n")
    _write(case / "constant" / "physicalProperties", "dictionary", "physicalProperties",
           f"viscosityModel constant;\nnu {nu:.9g};\n")

    # --- boundary conditions from the converged 1D solution
    flows = {f"outlet_b{i}": float(b.flow_ml_s[-1]) * 1e-6 for i, b in result.branches.items()}
    p_inlet = cfg.pa_mmhg * MMHG / rho
    u_bc = ["    lumen_wall { type noSlip; }", "    lumen_inlet { type pressureInletVelocity; value uniform (0 0 0); }",
            "    background { type noSlip; }"]
    p_bc = ["    lumen_wall { type zeroGradient; }", f"    lumen_inlet {{ type fixedValue; value uniform {p_inlet:.9g}; }}",
            "    background { type zeroGradient; }"]
    for n in outlets:
        u_bc.append(f"    lumen_{n} {{ type flowRateOutletVelocity; volumetricFlowRate constant {flows[n]:.9g}; "
                    "value uniform (0 0 0); }")
        p_bc.append(f"    lumen_{n} {{ type zeroGradient; }}")
    _write(case / "0" / "U", "volVectorField", "U", "dimensions [0 1 -1 0 0 0 0];\ninternalField uniform (0 0 0);\n"
           "boundaryField\n{\n" + "\n".join(u_bc) + "\n}\n")
    _write(case / "0" / "p", "volScalarField", "p", "dimensions [0 2 -2 0 0 0 0];\n"
           f"internalField uniform {p_inlet:.9g};\nboundaryField\n{{\n" + "\n".join(p_bc) + "\n}\n")
    allrun = case / "Allrun"
    allrun.write_text(f"""#!/bin/sh
# 3D steady CFD for FFR (OpenFOAM.com v2006+). Run inside the case directory.
set -e
cd "${{0%/*}}" || exit 1
blockMesh > log.blockMesh
surfaceFeatureExtract > log.surfaceFeatureExtract
if [ "${{NPROCS:-1}}" -gt 1 ]; then
    decomposePar -force > log.decomposePar
    mpirun -np "$NPROCS" snappyHexMesh -overwrite -parallel > log.snappyHexMesh
    mpirun -np "$NPROCS" checkMesh -parallel > log.checkMesh || true
    mpirun -np "$NPROCS" simpleFoam -parallel > log.simpleFoam
    reconstructPar -latestTime > log.reconstructPar
else
    snappyHexMesh -overwrite > log.snappyHexMesh
    checkMesh > log.checkMesh || true
    simpleFoam > log.simpleFoam
fi
echo "done; now: python -m vessel_code.ffr.openfoam results --case $(pwd)"
""")
    allrun.chmod(0o755)
    meta = {
        "rho": rho, "mu": mu, "pa_mmhg": cfg.pa_mmhg, "pv_mmhg": cfg.pv_mmhg, "artery_type": result.artery_type,
        "outlet_flow_m3_s": flows,
        "outlet_resistance_mmhg_s_per_ml": {f"outlet_b{i}": r for i, r in result.outlet_resistance.items()},
        "patches": patches, "voxel_mm": surface.voxel_mm, "refinement_level": refinement_level,
        "sample_index": sample_index, "sample_points_m": np.round(np.asarray(sample_points), 10).tolist(),
        "surface_checks": surface.checks,
        "ffr1d": {str(i): {"ffr": b.ffr.tolist(), "ffr_static": b.ffr_static.tolist(),
                           "distance_mm": b.distance_mm.tolist(), "name": b.name, "start": b.start}
                  for i, b in result.branches.items()},
        "coupling_iteration": 0,
    }
    (case / "ffr3d_case.json").write_text(json.dumps(meta, indent=1))
    return case


# ------------------------------------------------------------------------------------------
# Read-back


def _latest_dir(root: Path) -> Path | None:
    if not root.exists():
        return None
    times = []
    for d in root.iterdir():
        try:
            times.append((float(d.name), d))
        except ValueError:
            continue
    return max(times)[1] if times else None


def read_centreline_pressure(case: Path) -> np.ndarray:
    """[K,4] x,y,z (m), kinematic p from the latest centreline sample."""
    latest = _latest_dir(case / "postProcessing" / "sampleCentreline")
    if latest is None:
        raise FileNotFoundError(f"{case}: no postProcessing/sampleCentreline output; run ./Allrun first")
    files = sorted(latest.glob("centreline*p*.xy")) + sorted(latest.glob("centreline*.xy"))
    for f in files:
        rows = np.loadtxt(f, ndmin=2)
        if rows.shape[1] >= 4:
            return rows[:, :4]
    raise FileNotFoundError(f"{latest}: no centreline pressure file")


def read_patch_pressures(case: Path) -> dict:
    out = {}
    for d in (case / "postProcessing").glob("pAvg_*"):
        latest = _latest_dir(d)
        if latest is None:
            continue
        for f in latest.glob("*.dat"):
            rows = [l.split() for l in f.read_text().splitlines() if l.strip() and not l.startswith("#")]
            if rows:
                out[d.name[len("pAvg_"):]] = float(rows[-1][-1])
    return out


def results_3d(case, *, figure: bool = True) -> dict:
    """FFR_3D along the centreline (static pressure / Pa), compared with the 1D model."""
    from scipy.spatial import cKDTree
    case = Path(case)
    meta = json.loads((case / "ffr3d_case.json").read_text())
    rows = read_centreline_pressure(case)
    pa = meta["pa_mmhg"] * MMHG
    idx = meta["sample_index"]
    want = np.asarray(meta["sample_points_m"])
    # OpenFOAM drops requested points that fall outside the mesh: match by coordinates.
    d, j = cKDTree(rows[:, :3]).query(want)
    ok = d < 1e-6
    out = {}
    p = np.where(ok, rows[j, 3] * meta["rho"], np.nan)
    for (bi, si), val in zip(idx, p):
        out.setdefault(str(bi), {})[si] = val
    branches = {}
    for bi, one_d in meta["ffr1d"].items():
        n = len(one_d["ffr"])
        ffr3 = np.full(n, np.nan)
        for si, val in out.get(bi, {}).items():
            ffr3[si] = val / pa
        good = np.isfinite(ffr3)
        if good.sum() >= 2:
            k = np.arange(n)
            ffr3[~good] = np.interp(k[~good], k[good], ffr3[good])
        branches[bi] = {"name": one_d["name"], "distance_mm": one_d["distance_mm"], "ffr3d_static": ffr3.tolist(),
                        "ffr1d": one_d["ffr"], "ffr1d_static": one_d["ffr_static"], "start": one_d["start"],
                        "distal_ffr3d": float(ffr3[-1]), "distal_ffr1d": float(one_d["ffr"][-1]),
                        "sampled_fraction": float(good[one_d["start"]:].mean())}
    summary = {"case": str(case), "branches": branches,
               "outlet_pressure_mmhg": {k: v * meta["rho"] / MMHG for k, v in read_patch_pressures(case).items()}}
    (case / "ffr3d_results.json").write_text(json.dumps(summary, indent=1, allow_nan=True))
    if figure:
        plot_1d_vs_3d(summary, case / "ffr_1d_vs_3d.png")
    return summary


def plot_1d_vs_3d(summary: dict, path: Path) -> Path:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from vessel_code.ffr.visualize import INK, MUTED, _style
    items = list(summary["branches"].values())
    fig, axes = plt.subplots(1, len(items), figsize=(3.6 * len(items), 3.4), squeeze=False, layout="constrained")
    for ax, b in zip(axes[0], items):
        st = b["start"]
        x = np.asarray(b["distance_mm"])[st:]
        ax.axhline(0.80, color=MUTED, ls="--", lw=1)
        ax.plot(x, np.asarray(b["ffr1d"])[st:], color=INK, lw=2, label="1D (recovered)")
        ax.plot(x, np.asarray(b["ffr3d_static"])[st:], color="#eb6834", lw=2, label="3D (static)")
        ax.set_title(f"{b['name']}: 1D {b['distal_ffr1d']:.2f} / 3D {b['distal_ffr3d']:.2f}", fontsize=9, loc="left")
        ax.set_xlabel("distance from ostium (mm)", fontsize=8)
        _style(ax)
    axes[0, 0].set_ylabel("FFR")
    axes[0, 0].legend(fontsize=8, frameon=False)
    fig.savefig(path, dpi=150, facecolor="white")
    plt.close(fig)
    return path


def update_outlet_flows(case, *, relaxation: float = 0.7) -> dict:
    """One 1D-3D coupling step: Q_i <- (1-w) Q_i + w (P_i^3D - Pv) / R_i, rewrite 0/U (and latest time U)."""
    case = Path(case)
    meta = json.loads((case / "ffr3d_case.json").read_text())
    pressures = read_patch_pressures(case)
    rho, pv = meta["rho"], meta["pv_mmhg"]
    new = {}
    for name, q in meta["outlet_flow_m3_s"].items():
        if name not in pressures:
            new[name] = q
            continue
        p_mmhg = pressures[name] * rho / MMHG
        r = meta["outlet_resistance_mmhg_s_per_ml"][name]
        target = max(p_mmhg - pv, 0.0) / r * 1e-6
        new[name] = (1 - relaxation) * q + relaxation * target
    targets = [case / "0" / "U"]
    latest = _latest_dir(case)
    if latest is not None and (latest / "U").exists():
        targets.append(latest / "U")
    for f in targets:
        text = f.read_text()
        for name, q in new.items():
            key = f"lumen_{name}"
            if key in text:
                head, tail = text.split(key, 1)
                before, after = tail.split("volumetricFlowRate", 1)
                rest = after.split(";", 1)[1]
                text = head + key + before + f"volumetricFlowRate constant {q:.9g};" + rest
        f.write_text(text)
    change = max(abs(new[k] - meta["outlet_flow_m3_s"][k]) / max(meta["outlet_flow_m3_s"][k], 1e-15) for k in new)
    meta["outlet_flow_m3_s"] = new
    meta["coupling_iteration"] += 1
    (case / "ffr3d_case.json").write_text(json.dumps(meta, indent=1))
    return {"iteration": meta["coupling_iteration"], "max_relative_flow_change": change, "flows_m3_s": new}


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=("results", "update-flows"))
    ap.add_argument("--case", required=True, type=Path)
    args = ap.parse_args(argv)
    if args.command == "results":
        s = results_3d(args.case)
        for b in s["branches"].values():
            print(f"{b['name']}: distal FFR 3D {b['distal_ffr3d']:.3f} | 1D {b['distal_ffr1d']:.3f} "
                  f"(sampled {100 * b['sampled_fraction']:.0f}%)")
    else:
        print(json.dumps(update_outlet_flows(args.case), indent=1))


if __name__ == "__main__":
    main()
